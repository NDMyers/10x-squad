'use strict';

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { StringDecoder } = require('node:string_decoder');

const GENERATED_MARKER = '<!-- generated by 10x-squad record-cost; re-run to refresh, do not edit by hand -->';
const MAIN_AGENT = 'main';
const RELEVANT_TYPES = new Set([
  'session.usage_record',
  'subagent.started',
  'user.message',
  'session.compaction_complete',
]);

function* readLines(filePath) {
  const fd = fs.openSync(filePath, 'r');
  try {
    const buffer = Buffer.allocUnsafe(1 << 20);
    const decoder = new StringDecoder('utf8');
    let carry = '';
    let bytes;
    while ((bytes = fs.readSync(fd, buffer, 0, buffer.length, null)) > 0) {
      const parts = (carry + decoder.write(buffer.subarray(0, bytes))).split('\n');
      carry = parts.pop();
      for (const line of parts) {
        if (line) yield line;
      }
    }
    carry += decoder.end();
    if (carry) yield carry;
  } finally {
    fs.closeSync(fd);
  }
}

function parseRelevantEvent(line) {
  const match = /^\{"type":"([^"]+)"/.exec(line);
  if (match && !RELEVANT_TYPES.has(match[1])) return null;
  try {
    const event = JSON.parse(line);
    return RELEVANT_TYPES.has(event.type) ? event : null;
  } catch {
    return null;
  }
}

function personaOf(agentName) {
  if (!agentName) return 'unknown';
  return agentName.startsWith('10x-') ? agentName.slice(4) : agentName;
}

function newAgent(id) {
  return {
    id,
    persona: id === MAIN_AGENT ? 'vivaldi' : 'unknown',
    dispatched_model: null,
    calls: [],
    followUps: 0,
    compactions: 0,
  };
}

function toCall(event, segment) {
  const usage = event.data.usage;
  const copilotUsage = usage.copilotUsage;
  const details = (copilotUsage && copilotUsage.tokenDetails || []).map((detail) => ({
    type: detail.tokenType,
    count: detail.tokenCount || 0,
    rate: detail.batchSize ? detail.costPerBatch / detail.batchSize : 0,
  }));
  return {
    at: event.timestamp,
    atMs: Date.parse(event.timestamp),
    model: usage.model,
    effort: usage.reasoningEffort || null,
    inputTokens: usage.inputTokens || 0,
    outputTokens: usage.outputTokens || 0,
    toolCalls: usage.numToolCalls || 0,
    durationMs: usage.duration || 0,
    credits: copilotUsage && Number.isFinite(copilotUsage.totalNanoAiu) ? copilotUsage.totalNanoAiu / 1e9 : null,
    details,
    segment,
  };
}

function lowestRates(agents) {
  const lowest = new Map();
  for (const agent of agents) {
    for (const call of agent.calls) {
      for (const detail of call.details) {
        const key = `${call.model}\u0000${detail.type}`;
        if (!lowest.has(key) || detail.rate < lowest.get(key)) lowest.set(key, detail.rate);
      }
    }
  }
  return lowest;
}

function premiumCredits(call, lowest) {
  let nano = 0;
  for (const detail of call.details) {
    nano += detail.count * Math.max(0, detail.rate - lowest.get(`${call.model}\u0000${detail.type}`));
  }
  return nano / 1e9;
}

function mostCommon(values) {
  const counts = new Map();
  for (const value of values) {
    if (value) counts.set(value, (counts.get(value) || 0) + 1);
  }
  let best = null;
  for (const [value, count] of counts) {
    if (best === null || count > counts.get(best)) best = value;
  }
  return best;
}

function summarizeAgent(agent, lowest) {
  const calls = agent.calls;
  const segments = new Map();
  let credits = 0;
  let premiumCalls = 0;
  let premiumSurcharge = 0;
  let uncostedCalls = 0;
  let peakContext = 0;
  let toolCalls = 0;
  let modelMs = 0;

  for (const call of calls) {
    peakContext = Math.max(peakContext, call.inputTokens);
    toolCalls += call.toolCalls;
    modelMs += call.durationMs;
    const segment = segments.get(call.segment) || { calls: 0, credits: 0, first: call.atMs, last: call.atMs };
    segment.calls += 1;
    segment.first = Math.min(segment.first, call.atMs);
    segment.last = Math.max(segment.last, call.atMs);
    if (call.credits === null) {
      uncostedCalls += 1;
    } else {
      credits += call.credits;
      segment.credits += call.credits;
      const surcharge = premiumCredits(call, lowest);
      if (surcharge > 0) {
        premiumCalls += 1;
        premiumSurcharge += surcharge;
      }
    }
    segments.set(call.segment, segment);
  }

  const first = calls.reduce((min, call) => Math.min(min, call.atMs), Infinity);
  const last = calls.reduce((max, call) => Math.max(max, call.atMs), -Infinity);
  const models = [...new Set(calls.map((call) => call.model))];

  return {
    agent_id: agent.id,
    persona: agent.persona,
    model: agent.dispatched_model || mostCommon(calls.map((call) => call.model)),
    models,
    reasoning_effort: mostCommon(calls.map((call) => call.effort)),
    calls: calls.length,
    uncosted_calls: uncostedCalls,
    tool_calls: toolCalls,
    credits,
    peak_context_tokens: peakContext,
    premium_rate_calls: premiumCalls,
    premium_surcharge_credits: premiumSurcharge,
    compactions: agent.compactions,
    follow_up_prompts: agent.followUps,
    first_at: new Date(first).toISOString(),
    last_at: new Date(last).toISOString(),
    span_ms: last - first,
    model_time_ms: modelMs,
    prompts: [...segments.entries()]
      .sort(([a], [b]) => a - b)
      .map(([index, segment]) => ({
        prompt: index,
        calls: segment.calls,
        credits: segment.credits,
        span_ms: segment.last - segment.first,
      })),
  };
}

function summarizeUsageEvents(eventsPath, { since } = {}) {
  const sinceMs = since === undefined ? -Infinity : Date.parse(since);
  if (since !== undefined && !Number.isFinite(sinceMs)) {
    throw new Error(`--since must be an ISO timestamp, got: ${since}`);
  }

  const agents = new Map();
  const agentFor = (id) => {
    if (!agents.has(id)) agents.set(id, newAgent(id));
    return agents.get(id);
  };

  for (const line of readLines(eventsPath)) {
    const event = parseRelevantEvent(line);
    if (!event || !(Date.parse(event.timestamp) >= sinceMs)) continue;
    const id = event.agentId || MAIN_AGENT;

    if (event.type === 'subagent.started') {
      const agent = agentFor(event.agentId || event.data.toolCallId);
      agent.persona = personaOf(event.data.agentName);
      agent.dispatched_model = event.data.model || null;
    } else if (event.type === 'session.usage_record') {
      if (!event.data || !event.data.usage) continue;
      const agent = agentFor(id);
      agent.calls.push(toCall(event, agent.followUps));
    } else if (event.type === 'user.message' && id !== MAIN_AGENT) {
      const agent = agentFor(id);
      if (agent.calls.length > 0 || agent.initialPromptSeen) agent.followUps += 1;
      agent.initialPromptSeen = true;
    } else if (event.type === 'session.compaction_complete' && event.data.success !== false) {
      agentFor(id).compactions += 1;
    }
  }

  const withCalls = [...agents.values()].filter((agent) => agent.calls.length > 0);
  const lowest = lowestRates(withCalls);
  const rows = withCalls
    .map((agent) => summarizeAgent(agent, lowest))
    .sort((a, b) => Date.parse(a.first_at) - Date.parse(b.first_at));

  const sum = (key) => rows.reduce((total, row) => total + row[key], 0);
  const dispatches = rows.filter((row) => row.agent_id !== MAIN_AGENT);
  const firstAt = rows.length ? rows.reduce((min, row) => (row.first_at < min ? row.first_at : min), rows[0].first_at) : null;
  const lastAt = rows.length ? rows.reduce((max, row) => (row.last_at > max ? row.last_at : max), rows[0].last_at) : null;

  return {
    rows,
    totals: {
      dispatches: dispatches.length,
      follow_up_prompts: dispatches.reduce((total, row) => total + row.follow_up_prompts, 0),
      calls: sum('calls'),
      uncosted_calls: sum('uncosted_calls'),
      tool_calls: sum('tool_calls'),
      credits: sum('credits'),
      premium_rate_calls: sum('premium_rate_calls'),
      premium_surcharge_credits: sum('premium_surcharge_credits'),
      first_at: firstAt,
      last_at: lastAt,
      span_ms: firstAt ? Date.parse(lastAt) - Date.parse(firstAt) : 0,
    },
  };
}

function formatCredits(value) {
  return value >= 100
    ? Math.round(value).toLocaleString('en-US')
    : value.toFixed(1);
}

function formatCount(value) {
  return value.toLocaleString('en-US');
}

function formatTokens(value) {
  return value >= 1000 ? `${Math.round(value / 1000)}k` : String(value);
}

function formatSpan(ms) {
  const totalMinutes = Math.round(ms / 60000);
  if (totalMinutes < 1) return `${Math.round(ms / 1000)}s`;
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  return hours ? `${hours}h${String(minutes).padStart(2, '0')}m` : `${minutes}m`;
}

function titleCase(value) {
  return value ? value[0].toUpperCase() + value.slice(1) : value;
}

function renderCostMarkdown(summary, { title, source, since } = {}) {
  const { rows, totals } = summary;
  const lines = [
    GENERATED_MARKER,
    `# Squad dispatch cost${title ? ` — ${title}` : ''}`,
    '',
    `Source: ${source || 'session telemetry'}${since ? `, events since ${since}` : ''}. Credits are the harness's own usage accounting, not tokens; they price cached input, fresh input and output separately.`,
    '',
    '| Persona | Model | Effort | Calls | Credits | Share | Peak context | Premium-rate calls | Compactions | Follow-up prompts | Span |',
    '|---|---|---|---:|---:|---:|---:|---:|---:|---:|---:|',
  ];

  for (const row of rows) {
    const share = totals.credits > 0 ? `${Math.round((row.credits / totals.credits) * 100)}%` : '—';
    const premium = row.premium_rate_calls
      ? `${formatCount(row.premium_rate_calls)} of ${formatCount(row.calls)} (+${formatCredits(row.premium_surcharge_credits)})`
      : '0';
    lines.push(
      `| ${titleCase(row.persona)}${row.agent_id === MAIN_AGENT ? ' (orchestrator)' : ''} | \`${row.model}\` | ${row.reasoning_effort || '—'} | ${formatCount(row.calls)} | ${formatCredits(row.credits)} | ${share} | ${formatTokens(row.peak_context_tokens)} | ${premium} | ${row.compactions} | ${row.agent_id === MAIN_AGENT ? '—' : row.follow_up_prompts} | ${formatSpan(row.span_ms)} |`
    );
  }

  lines.push(
    '',
    `**Totals:** ${totals.dispatches} dispatches and ${totals.follow_up_prompts} follow-up prompts to resumed dispatches; ${formatCount(totals.calls)} model calls; ${formatCredits(totals.credits)} credits; first to last call ${formatSpan(totals.span_ms)}, including waits. Premium-rate calls (billed above the lowest per-token rate this session saw for the same model, which is how a context-size price step shows up) added ${formatCredits(totals.premium_surcharge_credits)} credits across ${formatCount(totals.premium_rate_calls)} calls.`
  );
  if (totals.uncosted_calls > 0) {
    lines.push('', `${totals.uncosted_calls} calls reported no credits and are counted as calls only — the credit total is a floor, not a full cost.`);
  }

  const resumed = rows.filter((row) => row.follow_up_prompts > 0);
  if (resumed.length > 0) {
    lines.push('', '## Work between prompts', '', 'Each follow-up prompt starts a new stretch of work in a dispatch that keeps its context. A stretch with no call or time budget is where cost grows unseen.', '', '| Persona | Stretch | Calls | Credits | Span |', '|---|---|---:|---:|---:|');
    for (const row of resumed) {
      for (const prompt of row.prompts) {
        const label = prompt.prompt === 0 ? 'initial dispatch' : `follow-up ${prompt.prompt}`;
        lines.push(`| ${titleCase(row.persona)} \`${row.agent_id.slice(0, 8)}\` | ${label} | ${formatCount(prompt.calls)} | ${formatCredits(prompt.credits)} | ${formatSpan(prompt.span_ms)} |`);
      }
    }
  }

  return `${lines.join('\n')}\n`;
}

function resolveEventsPath({ eventsPath, sessionId, env = process.env, homeDir = os.homedir() } = {}) {
  if (eventsPath) return { path: path.resolve(eventsPath), sessionId: sessionId || null };
  const id = sessionId || env.COPILOT_AGENT_SESSION_ID;
  if (!id) return null;
  const stateRoot = env.COPILOT_HOME
    ? path.join(env.COPILOT_HOME, 'session-state')
    : path.join(homeDir, '.copilot', 'session-state');
  return { path: path.join(stateRoot, id, 'events.jsonl'), sessionId: id };
}

function recordCost({ projectDirectory, eventsPath, sessionId, since, overwrite = false, env, homeDir } = {}) {
  const resolved = resolveEventsPath({ eventsPath, sessionId, env, homeDir });
  if (!resolved || !fs.existsSync(resolved.path)) {
    return {
      ok: false,
      errors: [{
        code: 'TELEMETRY_UNAVAILABLE',
        message: 'No session telemetry found. Write one cost.md row per dispatch from the harness usage block, using `not captured` for any figure it does not report.',
      }],
    };
  }

  const resolvedProject = path.resolve(projectDirectory);
  const costPath = path.join(resolvedProject, 'cost.md');
  if (fs.existsSync(costPath) && !overwrite) {
    const existing = fs.readFileSync(costPath, 'utf8');
    if (existing.trim() && !existing.startsWith(GENERATED_MARKER)) {
      return {
        ok: false,
        errors: [{
          code: 'COST_FILE_NOT_GENERATED',
          message: 'cost.md has hand-written rows. Pass --overwrite true to replace it with recorded telemetry.',
        }],
      };
    }
  }

  const summary = summarizeUsageEvents(resolved.path, { since });
  if (summary.rows.length === 0) {
    return {
      ok: false,
      errors: [{ code: 'NO_USAGE_RECORDED', message: `No usage records in ${resolved.path}${since ? ` since ${since}` : ''}.` }],
    };
  }

  let slug = path.basename(resolvedProject);
  try {
    slug = JSON.parse(fs.readFileSync(path.join(resolvedProject, 'project.json'), 'utf8')).slug || slug;
  } catch {}

  fs.mkdirSync(resolvedProject, { recursive: true });
  fs.writeFileSync(
    costPath,
    renderCostMarkdown(summary, {
      title: slug,
      source: `Copilot session ${resolved.sessionId || path.basename(path.dirname(resolved.path))}`,
      since,
    })
  );

  return {
    ok: true,
    cost_path: costPath,
    events_path: resolved.path,
    totals: summary.totals,
    dispatches: summary.rows.map((row) => ({
      persona: row.persona,
      agent_id: row.agent_id,
      model: row.model,
      calls: row.calls,
      credits: Number(row.credits.toFixed(3)),
      peak_context_tokens: row.peak_context_tokens,
      premium_rate_calls: row.premium_rate_calls,
      compactions: row.compactions,
      follow_up_prompts: row.follow_up_prompts,
      span_ms: row.span_ms,
    })),
    errors: [],
  };
}

module.exports = {
  GENERATED_MARKER,
  recordCost,
  renderCostMarkdown,
  resolveEventsPath,
  summarizeUsageEvents,
};
